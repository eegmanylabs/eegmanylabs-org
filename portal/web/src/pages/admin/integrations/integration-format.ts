/** A synchronised value as a person reads it. No value is said in words, never as an empty string. */
export function valueText(value: string | null | undefined): string {
  return displayCanonical(value) ?? "No value";
}

/** A stored code in words, for a code that a newer version of the functions may add. */
export function labelOf<K extends string>(labels: Readonly<Record<K, string>>, code: string): string {
  return (labels as Readonly<Record<string, string>>)[code] ?? code;
}

/** The statistics of a run worth showing: the counts above zero, in words. */
export function statLines(stats: Readonly<Record<string, number>>): readonly string[] {
  return Object.entries(stats)
    .filter(([, count]) => count > 0)
    .map(([key, count]) => `${STAT_LABELS[key] ?? key}: ${count}`);
}
