/**
 * What a connection's state means and what clears it, naming what it writes to: Google, or the
 * synthetic fake of the emulator.
 */
export function connectionHint(status: IntegrationConnectionStatus, adapter: "none" | "fake" | "real"): string {
  const hint = CONNECTION_STATUS_HINTS[status];
  return adapter === "fake" ? hint.replace("to Google", "to the synthetic fake") : hint;
}

