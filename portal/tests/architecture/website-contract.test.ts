// The column contract of the public website's data files (docs/INTEGRATIONS.md, section 6): the
// generator, given the committed files and records that state exactly what the files say,
// writes every file back byte for byte, line endings included. The files are public and part of
// this repository, which the test reads and never changes.
import { readFileSync } from "node:fs";
import path from "node:path";
import {
  cellOf,
  generateWebsiteFiles,
  isWebsiteStagePair,
  type PublicInputs,
  parseTsv,
  publicProjection,
  WEBSITE_FILES,
  WEBSITE_STAGES,
} from "@eegml/shared";
import { describe, expect, it } from "vitest";
import { PORTAL_ROOT } from "./support";

const REPOSITORY_ROOT = path.resolve(PORTAL_ROOT, "..");

function committed(key: "replications" | "publications" | "people" | "members"): string {
  return readFileSync(path.join(REPOSITORY_ROOT, WEBSITE_FILES[key].path), "utf8");
}

const base = {
  replications: committed("replications"),
  publications: committed("publications"),
  people: committed("people"),
  members: committed("members"),
};

/** Records that state what the committed files say, as an import of them would leave them. */
function recordsFromFiles(): PublicInputs {
  const people = parseTsv(base.people);
  const members = parseTsv(base.members);
  const replications = parseTsv(base.replications);
  const live = { archivedAt: null, dataOrigin: "importedHistorical" };
  const nonEmpty = (value: string) => (value === "" ? undefined : value);
  const defined = (values: Record<string, unknown>) =>
    Object.fromEntries(Object.entries(values).filter(([, value]) => value !== undefined));
  return {
    persons: [
      ...people.lines.map((line) =>
        publicProjection(
          "person",
          `core-${cellOf(people, line, "PersonId")}`,
          defined({
            ...live,
            websitePersonId: cellOf(people, line, "PersonId"),
            displayName: nonEmpty(cellOf(people, line, "FullName")),
            affiliationSummary: nonEmpty(cellOf(people, line, "Affiliation")),
            countrySource: nonEmpty(cellOf(people, line, "Country")),
            headshotFilename: nonEmpty(cellOf(people, line, "HeadShotFilename")),
            scholarUrl: nonEmpty(cellOf(people, line, "ScholarUrl")),
            universityUrl: nonEmpty(cellOf(people, line, "UniUrl")),
            labUrl: nonEmpty(cellOf(people, line, "LabUrl")),
            publicListing: "coreTeam",
          }),
        ),
      ),
      ...members.lines.map((line) =>
        publicProjection(
          "person",
          `member-${cellOf(members, line, "PersonId")}`,
          defined({
            ...live,
            websitePersonId: cellOf(members, line, "PersonId"),
            displayName: nonEmpty(cellOf(members, line, "FullName")),
            affiliationSummary: nonEmpty(cellOf(members, line, "Affiliation")),
            countrySource: nonEmpty(cellOf(members, line, "Country")),
            publicListing: "member",
          }),
        ),
      ),
    ],
    replications: replications.lines.map((line) => {
      const signup = cellOf(replications, line, "SignupUrl");
      const active = cellOf(replications, line, "SignUpActive") === "1";
      return publicProjection(
        "replication",
        cellOf(replications, line, "StudyId"),
        defined({
          ...live,
          studyKey: cellOf(replications, line, "StudyId"),
          theme: nonEmpty(cellOf(replications, line, "Theme")),
          psychConstruct: nonEmpty(cellOf(replications, line, "PsychConstruct")),
          publicStageText: nonEmpty(cellOf(replications, line, "LongStageText")),
          publicStageName: nonEmpty(cellOf(replications, line, "StageName")),
          publicStageNumber: Number.parseInt(cellOf(replications, line, "StageNumber"), 10),
          signupActive: active,
          signupUrl: active ? signup : undefined,
        }),
      );
    }),
    laboratories: [],
    participations: [],
    manuscripts: [],
    summaries: [],
  };
}

describe("the website's data files", () => {
  it("are regenerated byte for byte from records that state what they say", () => {
    const { files } = generateWebsiteFiles(base, recordsFromFiles(), {
      outputs: ["members", "replications", "publications"],
      origins: ["live", "importedHistorical"],
    });
    expect(files.people).toBe(base.people);
    expect(files.members).toBe(base.members);
    expect(files.replications).toBe(base.replications);
    expect(files.publications).toBe(base.publications);
  });
});

describe("the stages of a replication", () => {
  // The filter chips of the replications page name the stages as `StageNumber_StageName`.
  const chips = [
    ...readFileSync(path.join(REPOSITORY_ROOT, "theme", "templates", "page.jinja2"), "utf8").matchAll(
      /data-filter-key="stage" data-filter-value="([^"]+)"/g,
    ),
  ]
    .map((match) => match[1] ?? "")
    .filter((value) => value !== "");

  it("are the stages that the website's filters know, no more and no fewer", () => {
    expect(WEBSITE_STAGES.map((stage) => `${stage.number}_${stage.key}`).sort()).toEqual([...chips].sort());
  });

  it("of every committed row are stages the website knows, each with the tag the card shows", () => {
    const table = parseTsv(base.replications);
    for (const line of table.lines) {
      const number = cellOf(table, line, "StageNumber");
      const name = cellOf(table, line, "StageName");
      expect(isWebsiteStagePair(number, name)).toBe(true);
      expect(WEBSITE_STAGES.find((stage) => stage.key === name)?.longText).toBe(cellOf(table, line, "LongStageText"));
    }
  });

  it("are never written as a value the website does not know", () => {
    const { files, notes } = generateWebsiteFiles(
      base,
      {
        ...recordsFromFiles(),
        replications: [
          publicProjection("replication", "Synthetic2099", {
            archivedAt: null,
            dataOrigin: "live",
            studyKey: "Synthetic2099",
            publicStageName: "Data collection",
            publicStageNumber: 3,
          }),
          publicProjection("replication", "Synthetic2098", {
            archivedAt: null,
            dataOrigin: "live",
            studyKey: "Synthetic2098",
            publicStageName: "data_collection",
          }),
        ],
      },
      { outputs: ["replications"], origins: ["live"] },
    );
    const table = parseTsv(files.replications ?? "");
    const row = (id: string) => table.lines.find((line) => cellOf(table, line, "StudyId") === id);
    const unknown = row("Synthetic2099");
    const known = row("Synthetic2098");
    // A new replication without a stage the website knows is not added at all.
    expect(unknown).toBeUndefined();
    expect(notes.join(" ")).toContain("Synthetic2099");
    expect(
      known === undefined ? null : [cellOf(table, known, "StageNumber"), cellOf(table, known, "LongStageText")],
    ).toEqual(["6", "IPA acquired. Data collection ongoing"]);
  });
});
